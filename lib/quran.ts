import "server-only";
import { readFile } from "node:fs/promises";
import { join } from "node:path";
import chaptersJson from "@/data/quran/chapters.json";
import { juzOf } from "@/lib/constants";
import type { Chapter, SurahData, Verse } from "@/lib/types";

const chapters = chaptersJson as unknown as Chapter[];

export function getChapters(): Chapter[] {
  return chapters;
}

export function getChapter(id: number): Chapter | undefined {
  return chapters[id - 1];
}

export function isValidSurahId(id: number): boolean {
  return Number.isInteger(id) && id >= 1 && id <= 114;
}

/** Reads a surah from the bundled dataset (see scripts/build-quran-data.mjs). */
export async function getSurah(id: number): Promise<SurahData> {
  const file = join(process.cwd(), "data", "quran", "surah", `${id}.json`);
  return JSON.parse(await readFile(file, "utf8")) as SurahData;
}

/** Al-Mukhtasar explanation per ayah for a surah (generated by scripts/build-study-data.mjs). */
export async function getTafsir(lang: string, id: number): Promise<string[]> {
  const file = join(process.cwd(), "public", "data", "tafsir", lang, `${id}.json`);
  return JSON.parse(await readFile(file, "utf8")) as string[];
}


export interface VerseRef {
  /** Surah number. */
  s: number;
  verse: Verse;
}

let allVerses: Promise<VerseRef[]> | null = null;
/** Every ayah in mushaf order (loaded once per server process; used by juz and page landing pages). */
export function getAllVerses(): Promise<VerseRef[]> {
  return (allVerses ??= Promise.all(chapters.map((c) => getSurah(c.id))).then((all) =>
    all.flatMap((d, i) => d.verses.map((verse) => ({ s: i + 1, verse }))),
  ));
}

/** The ayat printed on one page (1–604) of the Madani mushaf. */
export async function getMushafPage(page: number): Promise<VerseRef[]> {
  return (await getAllVerses()).filter((r) => r.verse.p === page);
}

/** The ayat of one juzʾ (1–30). */
export async function getJuz(juz: number): Promise<VerseRef[]> {
  return (await getAllVerses()).filter((r) => juzOf(r.s, r.verse.n) === juz);
}

/** A translation of one surah (one string per ayah), for the localized pages. English comes from the surah file. */
export async function getTranslation(lang: string, id: number): Promise<string[]> {
  if (lang === "en") return (await getSurah(id)).verses.map((v) => v.en);
  const file = join(process.cwd(), "public", "data", "translations", lang, `${id}.json`);
  return JSON.parse(await readFile(file, "utf8")) as string[];
}
