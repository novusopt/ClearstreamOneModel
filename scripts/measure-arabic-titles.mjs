#!/usr/bin/env node
/**
 * Measures the page-header Arabic titles (114 surah names, "الجزء ١" … "الجزء ٣٠") in Amiri Quran and
 * writes their widths in em to lib/arabic-title-widths.ts. The headers give the title that width, so
 * the title column beside it lays out the same before and after the font loads (the fallback font is
 * wider: the badges re-wrapped when Amiri arrived, a 28 px layout shift on phones).
 *
 * Needs a running build (npm run build && npx next start) and Playwright:
 *   node scripts/measure-arabic-titles.mjs [http://localhost:3000]
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const { chromium } = createRequire(import.meta.url)("playwright");
const base = process.argv[2] ?? "http://localhost:3000";
const DIGITS = "٠١٢٣٤٥٦٧٨٩";
const chapters = JSON.parse(readFileSync("data/quran/chapters.json", "utf8"));
const titles = [...chapters.map((c) => c.nameArabic), ...Array.from({ length: 30 }, (_, i) => `الجزء ${String(i + 1).replace(/\d/g, (d) => DIGITS[d])}`)];

const browser = await chromium.launch();
const page = await browser.newPage();
await page.goto(`${base}/surah/1`, { waitUntil: "networkidle" });
const widths = await page.evaluate(async (list) => {
  await document.fonts.ready;
  const el = document.createElement("span");
  el.className = "font-quran";
  Object.assign(el.style, { fontSize: "100px", whiteSpace: "nowrap", position: "absolute", visibility: "hidden" });
  el.dir = "rtl";
  document.body.append(el);
  el.textContent = list[0];
  const face = [...document.fonts].find((f) => /amiriQuran$/i.test(f.family.replace(/['"]/g, "")) || /amiri.?quran(?!.*la)/i.test(f.family));
  await face?.load();
  if (face?.status !== "loaded") throw new Error("Amiri Quran not loaded");
  return list.map((t) => {
    el.textContent = t;
    // Round up to the next 0.01em so the box never clips the glyphs.
    return Math.ceil(el.getBoundingClientRect().width) / 100 + 0.01;
  });
}, titles);
await browser.close();

const entries = titles.map((t, i) => `  ${JSON.stringify(t)}: ${widths[i].toFixed(2)},`).join("\n");
writeFileSync(
  "lib/arabic-title-widths.ts",
  `// Generated by scripts/measure-arabic-titles.mjs: width in em of each page-header Arabic title, set in Amiri Quran.
// Do not edit by hand.
export const ARABIC_TITLE_WIDTHS: Record<string, number> = {
${entries}
};

/** Inline style that reserves a header title's Amiri width, so the layout does not change when the font loads. */
export const arabicTitleStyle = (title: string) => {
  const em = ARABIC_TITLE_WIDTHS[title];
  return em ? { width: \`\${em}em\` } : undefined;
};
`,
);
console.log(`wrote ${titles.length} widths`);
